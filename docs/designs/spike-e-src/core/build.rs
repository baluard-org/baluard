//! Generates the pinned static keys at build time, deterministically, so the
//! native tests, the tether-responder server and the WASM module (baked into
//! the cdylib) all share identical key material.
use sha2::{Digest, Sha256};
use x25519_dalek::{PublicKey, StaticSecret};

fn x25519_pub(sk: &[u8; 32]) -> [u8; 32] {
    // NB: StaticSecret::from(sk).to_bytes() returns the SECRET bytes, not the
    // public key — PublicKey::from(&secret) does the base-point multiply.
    PublicKey::from(&StaticSecret::from(*sk)).to_bytes()
}

fn main() {
    let out_dir = std::env::var("OUT_DIR").unwrap();
    let mut i_sk = [0u8; 32];
    let mut r_sk = [0u8; 32];
    i_sk.copy_from_slice(&Sha256::digest(b"baluard spike-e initiator static (browser extension / device)"));
    r_sk.copy_from_slice(&Sha256::digest(b"baluard spike-e responder static (phone)"));

    let i_pk = x25519_pub(&i_sk);
    let r_pk = x25519_pub(&r_sk);

    let fmt = |k: &[u8; 32]| k.iter().fold(String::new(), |s, b| s + &format!("{b:#04x}, "));
    let src = format!(
        "// @generated by build.rs — pinned static keys (deterministic, from fixed seed strings)\n\
         pub const INITIATOR_STATIC_SK: [u8; 32] = [{}];\n\
         pub const INITIATOR_STATIC_PK: [u8; 32] = [{}];\n\
         pub const RESPONDER_STATIC_SK: [u8; 32] = [{}];\n\
         pub const RESPONDER_STATIC_PK: [u8; 32] = [{}];\n",
        fmt(&i_sk), fmt(&i_pk), fmt(&r_sk), fmt(&r_pk)
    );
    std::fs::write(format!("{out_dir}/pinned_keys.rs"), src).unwrap();
    println!("cargo:rerun-if-changed=build.rs");
}
