#!/usr/bin/env bash
# Regenerate desktop/src/lib/wordlist-{en,es}.js from the canonical wordlist
# sources embedded in the Rust crate (crates/baluard-core/src/generator/data/).
# Run after editing the .txt files. The JS files are build artifacts: do not
# hand-edit them.
set -euo pipefail
cd "$(dirname "$0")/.."

node - << 'JS'
const fs = require("fs");
const toWords = (raw) =>
  raw.split("\n").map((w) => w.trim()).filter(Boolean);
const emit = (name, header, words) => {
  const body = words
    .map((w) => `  ${JSON.stringify(w)},`)
    .join("\n");
  fs.writeFileSync(
    `desktop/src/lib/${name}`,
    `// GENERATED by scripts/gen-wordlists.sh — do not edit.\n${header}\nexport const WORDS_${name
      .replace("wordlist-", "")
      .replace(".js", "")
      .toUpperCase()} = [\n${body}\n];\n`,
  );
};
const en = toWords(
  fs.readFileSync("crates/baluard-core/src/generator/data/eff-en.txt", "utf8"),
);
const es = toWords(
  fs.readFileSync("crates/baluard-core/src/generator/data/bip39-es.txt", "utf8"),
);
emit(
  "wordlist-en.js",
  "// Merged EFF English wordlist (large + short, deduplicated, CC-BY-3.0).",
  en,
);
emit(
  "wordlist-es.js",
  "// BIP-39 Spanish word list (diacritics stripped, MIT).",
  es,
);
console.log(`wordlist-en.js: ${en.length} words, wordlist-es.js: ${es.length} words`);
JS
