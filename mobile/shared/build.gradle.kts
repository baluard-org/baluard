// shared: KMP module — Compose UI + business logic, consumed by androidApp + iosApp.
// Phase 1 scope: minimal hello-world calling the Rust `generate_recovery_phrase`
// via the UniFFI-generated Kotlin bindings (jniLibs shipped by the host build).
plugins {
    alias(libs.plugins.kotlinMultiplatform)
    alias(libs.plugins.composeMultiplatform)
    alias(libs.plugins.composeCompiler)
    alias(libs.plugins.androidLibrary)
    kotlin("plugin.serialization") version "2.0.21"
}

composeCompiler {
    stabilityConfigurationFiles.add(project.layout.projectDirectory.file("compose_compiler_config.conf"))
}

kotlin {
    androidTarget {
        compilerOptions {
            jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17)
        }
    }
    iosX64()
    iosArm64()
    iosSimulatorArm64()

    applyDefaultHierarchyTemplate()

    sourceSets {
        commonMain.dependencies {
            // Compose Multiplatform runtime (UI, material3).
            implementation(compose.runtime)
            implementation(compose.foundation)
            implementation(compose.material3)
            // Extended icons (ContentCopy, Visibility) for the detail screen;
            // R8 shrinks unused glyphs on release builds.
            implementation(compose.materialIconsExtended)
            implementation(compose.components.resources)
            // Coroutines for StateFlow / suspend FFI calls (UniFFI async).
            implementation("org.jetbrains.kotlinx:kotlinx-coroutines-core:1.9.0")
            // JSON builder/parser for the daemon-wire cipher payloads.
            implementation("org.jetbrains.kotlinx:kotlinx-serialization-json:1.7.3")
            // Lifecycle-event observation (LifecycleEventEffect) for B3 sync
            // glue: ON_START -> guarded pull, ON_STOP -> debounce flush.
            implementation("org.jetbrains.androidx.lifecycle:lifecycle-runtime-compose:2.8.4")

            // NOTE: the UniFFI-generated Kotlin bindings (package app.baluard.mobile)
            // are NOT a Maven dependency. They are source files generated by
            // `uniffi-bindgen` from the Rust cdylib and live under
            // `shared/src/commonMain/kotlin/generated/` (committed, regenerated
            // on Rust API change). See docs/dev/dev-setup-mobile.md for the gen step.
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
            implementation("org.jetbrains.kotlinx:kotlinx-coroutines-test:1.9.0")
        }
        androidMain.dependencies {
            implementation(libs.androidx.activity.compose)
            // B5 biometric quick unlock: BiometricPrompt ceremony over an
            // AndroidKeystore AES-GCM key wrapping the vault KEK. Fragment is
            // referenced directly (BiometricPrompt needs a FragmentActivity).
            implementation("androidx.biometric:biometric:1.1.0")
            // Passkey provider settings: CredentialManager's
            // createSettingsPendingIntent is the only supported entry into
            // the system's default-credential-provider picker.
            implementation("androidx.credentials:credentials:1.6.0")
            implementation("androidx.fragment:fragment-ktx:1.6.2")
            // UniFFI 0.28 generates JNA-backed Kotlin bindings (com.sun.jna.*).
            // The aar is the Android artifact; the binding is Android-only by
            // nature, so JNA lives here, not in commonMain.
            implementation("net.java.dev.jna:jna:5.14.0@aar")
            // Opt-in background sync (plan §3.5): WorkManager periodic job
            // running the Rust locked fetch (objects only, no unlock).
            implementation("androidx.work:work-runtime-ktx:2.9.1")
        }
    }
}

